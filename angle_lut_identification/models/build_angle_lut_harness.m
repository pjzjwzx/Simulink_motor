function dutyBlock = local_install_duty_nonideal(model, iabcMux)
dutyBlock = [model '/Stage1_Duty_Nonideal'];
add_block('simulink/Ports & Subsystems/Subsystem', dutyBlock, ...
    'Position', [1500 610 1690 720]);
local_delete_template_ports(dutyBlock);

add_block('simulink/Ports & Subsystems/In1', [dutyBlock '/duty_cmd'], ...
    'Port', '1', 'Position', [25 55 55 75]);
add_block('simulink/Ports & Subsystems/In1', [dutyBlock '/iabc_meas'], ...
    'Port', '2', 'Position', [25 120 55 140]);
% Dead-time polarity is an interval property.  The measured-current path
% otherwise runs at the inherited 5-us base step, which would make the
% effective duty change inside a 50-us PWM interval while the observer
% records only one value.  Freeze the polarity input at the PWM boundary
% so duty_effective and min_pulse_flag are genuinely interval-effective.
add_block('simulink/Discrete/Zero-Order Hold', ...
    [dutyBlock '/iabc_at_pwm_boundary'], ...
    'SampleTime', '[T_ident 0]', ...
    'Position', [90 110 190 150]);
add_block('simulink/Sources/Constant', [dutyBlock '/min_pulse_duty'], ...
    'Value', 'pwm_min_pulse_duty', 'Position', [75 180 155 210]);
add_block('simulink/Sources/Constant', [dutyBlock '/deadtime_s'], ...
    'Value', 'pwm_deadtime_s', 'Position', [75 225 155 255]);
add_block('simulink/Sources/Constant', [dutyBlock '/ident_period_s'], ...
    'Value', 'T_ident', 'Position', [75 270 155 300]);
add_block('simulink/Sources/Constant', [dutyBlock '/duty_min'], ...
    'Value', 'pwm_min_duty', 'Position', [75 315 155 345]);
add_block('simulink/Sources/Constant', [dutyBlock '/duty_max'], ...
    'Value', 'pwm_max_duty', 'Position', [75 360 155 390]);

algorithm = [dutyBlock '/Apply_Duty_Nonidealities'];
add_block('simulink/User-Defined Functions/MATLAB Function', algorithm, ...
    'Position', [250 85 470 300]);
root = sfroot;
chart = root.find('-isa', 'Stateflow.EMChart', 'Path', algorithm);
assert(isscalar(chart), 'Stage1:DutyAlgorithmCreationFailed', ...
    'Could not create the duty nonideality MATLAB Function.');
chart.Script = sprintf([ ...
    'function [duty_eff,min_pulse_flag] = f(duty_cmd,iabc,min_pulse,deadtime_s,ident_period_s,duty_min,duty_max)\n' ...
    'duty_eff = duty_cmd;\n' ...
    'min_pulse_flag = false;\n' ...
    'for k = 1:3\n' ...
    '    d = duty_cmd(k);\n' ...
    '    if (d > duty_min) && (d < duty_min + min_pulse)\n' ...
    '        duty_eff(k) = duty_min;\n' ...
    '        min_pulse_flag = true;\n' ...
    '    elseif (d < duty_max) && (d > duty_max - min_pulse)\n' ...
    '        duty_eff(k) = duty_max;\n' ...
    '        min_pulse_flag = true;\n' ...
    '    end\n' ...
    'end\n' ...
    'dead_fraction = deadtime_s / ident_period_s;\n' ...
    'for k = 1:3\n' ...
    '    duty_eff(k) = duty_eff(k) - dead_fraction*sign(iabc(k));\n' ...
    '    duty_eff(k) = min(max(duty_eff(k),duty_min),duty_max);\n' ...
    'end\n' ...
    'end\n']);

add_block('simulink/Ports & Subsystems/Out1', ...
    [dutyBlock '/duty_effective'], 'Port', '1', ...
    'Position', [550 120 580 140]);
add_block('simulink/Ports & Subsystems/Out1', ...
    [dutyBlock '/min_pulse_flag'], 'Port', '2', ...
    'Position', [550 205 580 225]);

add_line(dutyBlock, 'duty_cmd/1', 'Apply_Duty_Nonidealities/1', 'autorouting', 'on');
add_line(dutyBlock, 'iabc_meas/1', 'iabc_at_pwm_boundary/1', 'autorouting', 'on');
add_line(dutyBlock, 'iabc_at_pwm_boundary/1', ...
    'Apply_Duty_Nonidealities/2', 'autorouting', 'on');
add_line(dutyBlock, 'min_pulse_duty/1', 'Apply_Duty_Nonidealities/3', 'autorouting', 'on');
add_line(dutyBlock, 'deadtime_s/1', 'Apply_Duty_Nonidealities/4', 'autorouting', 'on');
add_line(dutyBlock, 'ident_period_s/1', 'Apply_Duty_Nonidealities/5', 'autorouting', 'on');
add_line(dutyBlock, 'duty_min/1', 'Apply_Duty_Nonidealities/6', 'autorouting', 'on');
add_line(dutyBlock, 'duty_max/1', 'Apply_Duty_Nonidealities/7', 'autorouting', 'on');
add_block('simulink/Signal Routing/Demux', ...
    [dutyBlock '/effective_duty_demux'], ...
    'Outputs', '3', 'Position', [475 80 480 165]);
add_block('simulink/Signal Routing/Mux', ...
    [dutyBlock '/effective_duty_1d'], ...
    'Inputs', '3', 'Position', [515 80 520 165]);
add_line(dutyBlock, 'Apply_Duty_Nonidealities/1', ...
    'effective_duty_demux/1', 'autorouting', 'on');
add_line(dutyBlock, 'effective_duty_demux/1', ...
    'effective_duty_1d/1', 'autorouting', 'on');
add_line(dutyBlock, 'effective_duty_demux/2', ...
    'effective_duty_1d/2', 'autorouting', 'on');
add_line(dutyBlock, 'effective_duty_demux/3', ...
    'effective_duty_1d/3', 'autorouting', 'on');
add_line(dutyBlock, 'effective_duty_1d/1', ...
    'duty_effective/1', 'autorouting', 'on');
add_line(dutyBlock, 'Apply_Duty_Nonidealities/2', 'min_pulse_flag/1', 'autorouting', 'on');

averageInverter = [model '/Average-Value Inverter'];
averagePorts = get_param(averageInverter, 'PortHandles');
local_delete_input_line_handle(averagePorts.Inport(1));
local_branch_to_port(model, [model '/PWM_and_Actuation'], 1, dutyBlock, 1);
local_branch_to_port(model, iabcMux, 1, dutyBlock, 2);
dutyPorts = get_param(dutyBlock, 'PortHandles');
add_line(model, dutyPorts.Outport(1), averagePorts.Inport(1), 'autorouting', 'on');

Simulink.BlockDiagram.arrangeSystem(dutyBlock, 'FullLayout', 'true');
end

