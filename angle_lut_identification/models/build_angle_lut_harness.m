function info = build_angle_lut_harness()
%BUILD_ANGLE_LUT_HARNESS Build the Stage-1 model without editing the source.
%
% The generated model is a save_system copy of
% FOC_fw_hifi_v1_0709backup.slx.  It adds a mechanical-domain encoder
% forward model, routes its selected electrical angle through the original
% controller latency block, and adds passive, phase-aligned logging taps.
%
% Numeric mode contracts:
%   sensor_mode       uint8(0) = LEGACY_ELECTRICAL
%                     uint8(1) = MECHANICAL_STAGE1 (saved default)
%   encoder_error_mode uint8(0) = off
%                      uint8(1) = fixed mechanical bias
%                      uint8(2) = periodic mechanical error (saved default)

thisFile = mfilename('fullpath');
modelsDir = fileparts(thisFile);
projectDir = fileparts(modelsDir);
repoRoot = fileparts(projectDir);

sourcePath = fullfile(repoRoot, 'FOC_fw_hifi_v1_0709backup.slx');
harnessPath = fullfile(modelsDir, 'angle_lut_harness.slx');
sourceModel = 'FOC_fw_hifi_v1_0709backup';
harnessModel = 'angle_lut_harness';

assert(isfile(sourcePath), 'Stage1:MissingSourceModel', ...
    'Source model not found: %s', sourcePath);

sourceHashBefore = local_sha256(sourcePath);

cacheRoot = fullfile(tempdir, 'codex_angle_lut_stage1');
if ~isfolder(cacheRoot)
    mkdir(cacheRoot);
end
Simulink.fileGenControl('set', ...
    'CacheFolder', cacheRoot, ...
    'CodeGenFolder', cacheRoot, ...
    'createDir', true);

if bdIsLoaded(harnessModel)
    close_system(harnessModel, 0);
end
if bdIsLoaded(sourceModel)
    close_system(sourceModel, 0);
end

load_system(sourcePath);
solverContract = local_solver_contract(sourceModel);
save_system(sourceModel, harnessPath);
close_system(sourceModel, 0);
load_system(harnessPath);

cleanupModel = onCleanup(@() local_close_without_saving(harnessModel));

assert(isequal(solverContract, local_solver_contract(harnessModel)), ...
    'Stage1:SolverContractChanged', ...
    'save_system copy did not preserve the solver contract.');

local_install_workspace_parameters(harnessModel);
local_parameterize_operating_point(harnessModel);
local_install_encoder_forward_model(harnessModel);
iabcMux = local_install_iabc_mux(harnessModel);
dutyNonideal = local_install_duty_nonideal(harnessModel, iabcMux);
plantVoltage = local_install_voltage_drop(harnessModel, iabcMux);
logNames = local_install_observer_taps( ...
    harnessModel, iabcMux, dutyNonideal, plantVoltage);

set_param(harnessModel, 'PreLoadFcn', '');
set_param(harnessModel, 'PostLoadFcn', '');
set_param(harnessModel, 'CloseFcn', '');

% Update once before saving so malformed ports or sample times fail here.
set_param(harnessModel, 'SimulationCommand', 'update');
assert(isequal(solverContract, local_solver_contract(harnessModel)), ...
    'Stage1:SolverContractChanged', ...
    'Harness edits changed the inherited solver contract.');

save_system(harnessModel, harnessPath);
close_system(harnessModel, 0);

sourceHashAfter = local_sha256(sourcePath);
assert(strcmpi(sourceHashBefore, sourceHashAfter), ...
    'Stage1:SourceModelModified', ...
    'The source model hash changed while building the harness.');

info = struct();
info.source_model = sourcePath;
info.harness_model = harnessPath;
info.source_sha256_before = sourceHashBefore;
info.source_sha256_after = sourceHashAfter;
info.source_unchanged = true;
info.sensor_mode_contract = struct( ...
    'LEGACY_ELECTRICAL', uint8(0), ...
    'MECHANICAL_STAGE1', uint8(1));
info.error_mode_contract = struct( ...
    'off', uint8(0), 'fixed', uint8(1), 'periodic', uint8(2));
info.logged_timeseries = logNames;
info.solver_contract = solverContract;

fprintf('Built %s\n', harnessPath);
fprintf('Source SHA256 unchanged: %s\n', sourceHashAfter);
fprintf('Logged timeseries: %s\n', strjoin(logNames, ', '));
end

function local_install_workspace_parameters(model)
mw = get_param(model, 'ModelWorkspace');

% Preserve the legacy parameter and make its zero value explicit.
mw.assignin('encoder_theta_offset_rad', 0);

mw.assignin('sensor_mode', uint8(1));
mw.assignin('encoder_error_mode', uint8(2));
mw.assignin('encoder_error_bias_m_rad', 0);
mw.assignin('encoder_error_amp1_m_rad', deg2rad(0.60));
mw.assignin('encoder_error_phase1_rad', 0);
mw.assignin('encoder_error_amp2_m_rad', deg2rad(0.30));
mw.assignin('encoder_error_phase2_rad', pi/4);
mw.assignin('theta0_e_rad', 0);

mw.assignin('angle_sample_period_s', 1 / mw.evalin('fpwm'));
mw.assignin('encoder_noise_std_m_rad', 0);
mw.assignin('encoder_noise_seed', uint32(20260818));
mw.assignin('stage1_current_noise_std_A', 0);
mw.assignin('stage1_current_noise_seed', uint32(20260818));
mw.assignin('stage1_ident_phase_s', mw.evalin('Ts'));
mw.assignin('T_ident', 1 / mw.evalin('fpwm'));
mw.assignin('stage1_overmod_epsilon', 1e-12);

% These variables existed in the source workspace but were not physically
% wired.  The harness connects them and saves zero defaults so legacy/off
% operation remains dynamically equivalent to the original model.
mw.assignin('pwm_min_pulse_duty', 0);
mw.assignin('pwm_deadtime_s', 0);
mw.assignin('inverter_voltage_drop_V', 0);

% The inherited block is labelled RPM, but its next gain is exactly 2*pi;
% its numerical input is therefore mechanical revolutions per second.
    mw.assignin('stage1_speed_target_rpm', 10/(2*pi));
    % Saved zero initial conditions preserve source-model startup when the
    % legacy-equivalence gate explicitly selects LEGACY_ELECTRICAL/off.
    % Stage 1 overrides these variables with a case equilibrium so its
    % evaluation interval does not include the source speed loop's long
    % operating-point acquisition transient.
    mw.assignin('stage1_speed_initial_revps', 0);
    mw.assignin('stage1_omega_m_initial_radps', 0);
    mw.assignin('stage1_speed_pi_initial_A', 0);
    mw.assignin('stage1_idq_initial_A', [0 0]);
    mw.assignin('stage1_load_torque_Nm', 0);
end

function local_parameterize_operating_point(model)
loadBlock = [model '/Constant16'];
assert(getSimulinkBlockHandle(loadBlock) > 0, ...
    'Stage1:MissingLoadBlock', 'Expected load block not found.');
set_param(loadBlock, 'Value', 'stage1_load_torque_Nm');

steps = find_system(model, 'SearchDepth', 1, 'BlockType', 'Step');
activeStep = '';
for k = 1:numel(steps)
    ports = get_param(steps{k}, 'PortHandles');
    lineHandle = get_param(ports.Outport, 'Line');
    if lineHandle == -1
        continue;
    end
    destinations = get_param(lineHandle, 'DstBlockHandle');
    for j = 1:numel(destinations)
        if destinations(j) == -1
            continue;
        end
        destinationName = get_param(destinations(j), 'Name');
        if contains(destinationName, 'Rate Limiter2')
            activeStep = steps{k};
            break;
        end
    end
    if ~isempty(activeStep)
        break;
    end
end
assert(~isempty(activeStep), 'Stage1:MissingSpeedStep', ...
    'Could not locate the closed-loop speed step.');
    set_param(activeStep, ...
        'Before', 'stage1_speed_initial_revps', ...
        'After', 'stage1_speed_target_rpm');

    rateLimiter = [model '/Discrete Rate Limiter2'];
    assert(getSimulinkBlockHandle(rateLimiter) > 0, ...
        'Stage1:MissingSpeedRateLimiter', ...
        'Expected active speed rate limiter not found.');
    set_param(rateLimiter, 'Vinit', 'stage1_speed_initial_revps');

    plant = [model '/Surface Mount PMSM'];
    assert(getSimulinkBlockHandle(plant) > 0, ...
        'Stage1:MissingPlant', 'Expected PMSM plant not found.');
    set_param(plant, ...
        'omega_init', 'stage1_omega_m_initial_radps', ...
        'idq0', 'stage1_idq_initial_A');

    speedPi = [model '/PID Controller2'];
    assert(getSimulinkBlockHandle(speedPi) > 0, ...
        'Stage1:MissingSpeedPI', 'Expected speed PI not found.');
    set_param(speedPi, 'InitialConditionForIntegrator', ...
        'stage1_speed_pi_initial_A');
end

